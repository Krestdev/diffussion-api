/**
 * Writes src/auth/permission-labels.ts from the UI's dictionaries (diffusion-ui's
 * app/locales/{en,fr,it}.json, else locales/: `permissions` and `permissionGroups`), so the core's
 * console shows Diffusion's permissions in the viewer's language (the catalogue is served by the
 * app-admin API). The UI repo is the sibling folder, or UI_REPO_PATH.
 *
 * The UI nests codes by dot, and keeps a longer sibling as a literal dotted key when the shorter
 * code is itself a label: `"incoming": {"update": "…", "update.draft": "…"}`. Both are flattened.
 *
 *   npm run permissions:labels
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ALL_PERMISSIONS } from '../src/auth/permissions';

const LANGUAGES = ['en', 'fr', 'it'] as const;
const ui =
  process.env.UI_REPO_PATH ?? join(__dirname, '..', '..', 'diffusion-ui');
const localesDir = existsSync(join(ui, 'app', 'locales'))
  ? join(ui, 'app', 'locales')
  : join(ui, 'locales');

type Tree = { [key: string]: string | Tree };

/** Every label of a tree under its full dotted code (nested and literal dotted keys alike). */
function flatten(tree: Tree, prefix = '', into = new Map<string, string>()) {
  for (const [key, value] of Object.entries(tree)) {
    const code = prefix ? `${prefix}.${key}` : key;
    if (typeof value === 'string') into.set(code, value);
    else flatten(value, code, into);
  }
  return into;
}

const dictionaries = LANGUAGES.map((language) => {
  const json = JSON.parse(
    readFileSync(join(localesDir, `${language}.json`), 'utf8'),
  ) as { permissions?: Tree; permissionGroups?: Record<string, string> };
  return {
    permissions: flatten(json.permissions ?? {}),
    groups: json.permissionGroups ?? {},
  };
});

const labels: Record<string, Record<string, string>> = {};
const missing: string[] = [];
for (const code of ALL_PERMISSIONS) {
  labels[code] = {};
  LANGUAGES.forEach((language, i) => {
    const text = dictionaries[i].permissions.get(code);
    if (text) labels[code][language] = text;
    else missing.push(`${language}:${code}`);
  });
}
const groups: Record<string, Record<string, string>> = {};
for (const group of new Set(ALL_PERMISSIONS.map((c) => c.split('.')[0]))) {
  groups[group] = {};
  LANGUAGES.forEach((language, i) => {
    const text = dictionaries[i].groups[group];
    if (text) groups[group][language] = text;
    else missing.push(`${language}:group ${group}`);
  });
}
if (missing.length) throw new Error(`missing labels: ${missing.join(', ')}`);

writeFileSync(
  join(__dirname, '..', 'src', 'auth', 'permission-labels.ts'),
  `// Generated by scripts/sync-permission-labels.ts from diffusion-ui's locales. Do not edit by hand.

/** Each permission's label in en, fr and it. */
export const PERMISSION_LABELS: Readonly<
  Record<string, Readonly<Record<'en' | 'fr' | 'it', string>>>
> = ${JSON.stringify(labels, null, 2)};

/** Each group's name (a code's first segment) in en, fr and it. */
export const PERMISSION_GROUP_LABELS: Readonly<
  Record<string, Readonly<Record<'en' | 'fr' | 'it', string>>>
> = ${JSON.stringify(groups, null, 2)};
`,
);
console.log(
  `permission-labels.ts: ${ALL_PERMISSIONS.length} permissions, ${Object.keys(groups).length} groups (from ${localesDir})`,
);
